"""Run eval suites across all agents and generate evals/leaderboard.md."""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "packages" / "core-python" / "src"))
sys.path.insert(0, str(ROOT / "cli" / "src"))

from agents_for_everything import discover_agents  # noqa: E402
from evals.harness.runner import evaluate_agent  # noqa: E402


def main() -> int:
    agents = discover_agents(ROOT)
    rows = []
    total_cases = 0
    total_passed = 0

    for aid, manifest in sorted(agents.items()):
        t0 = time.monotonic()
        summary = evaluate_agent(aid, repo_root=ROOT, provider_name="mock")
        ms = round((time.monotonic() - t0) * 1000, 1)
        total_cases += summary.total
        total_passed += summary.passed
        rows.append(
            {
                "agent_id": aid,
                "name": manifest.name,
                "priority": manifest.priority,
                "maturity": manifest.maturity,
                "safety": manifest.safety_level,
                "cases": summary.total,
                "passed": summary.passed,
                "pass_rate": summary.pass_rate,
                "latency_ms": ms,
                "tested_profiles": manifest.tested_with,
            }
        )

    reports_dir = ROOT / "evals" / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    (reports_dir / "leaderboard.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")

    md = [
        "# Evaluation Leaderboard",
        "",
        "> Auto-generated by `scripts/build_leaderboard.py` against offline deterministic suites (`mock` runner; run `afe test <id> --live` to benchmark cloud/local models).",
        "",
        f"- **Evaluated Agents:** {len(rows)}",
        f"- **Total Eval Cases:** {total_cases}",
        f"- **Overall Pass Rate:** {total_passed}/{total_cases} ({(total_passed / total_cases if total_cases else 1.0):.1%})",
        "",
        "| Agent ID | Priority | Maturity | Safety | Cases | Pass Rate | Latency (ms) | Tested Model Tiers |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        tiers = ", ".join(r["tested_profiles"]) if r["tested_profiles"] else "default"
        md.append(
            f"| `{r['agent_id']}` | {r['priority']} | `{r['maturity']}` | {r['safety']} | {r['passed']}/{r['cases']} | {r['pass_rate']:.0%} | {r['latency_ms']} | {tiers} |"
        )
    (ROOT / "evals" / "leaderboard.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"Leaderboard updated: {len(rows)} agents, {total_passed}/{total_cases} cases passed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
